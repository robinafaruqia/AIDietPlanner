const express = require('express');
const router = express.Router();
const mongoose = require('mongoose');
const MealPlan = require('../models/MealPlan');
const { generateWeeklyMealPlan, calculateDailyCalories } = require('../services/mealPlanner');
const { regenerateSingleDay, swapMeal } = require('../services/aiMealGenerator');
const { optionalAuth } = require('../middleware/auth');

function parseFiniteNumber(value) {
  const n = typeof value === 'number' ? value : Number(value);
  return Number.isFinite(n) ? n : null;
}

function parseBoolean(value, defaultValue = true) {
  if (value === undefined || value === null) return defaultValue;
  if (typeof value === 'boolean') return value;
  if (typeof value === 'string') {
    const v = value.trim().toLowerCase();
    if (v === 'true') return true;
    if (v === 'false') return false;
  }
  return defaultValue;
}

function normalizeHealthConditions(healthConditions) {
  const raw = Array.isArray(healthConditions)
    ? healthConditions
    : (healthConditions ? [healthConditions] : []);

  return raw
    .map(v => (v === null || v === undefined ? '' : String(v).trim()))
    .filter(Boolean)
    .slice(0, 5);
}

function getUserId(req) {
  return req.user ? req.user._id : null;
}

async function saveMealPlanToDatabase(weight, height, conditions, mealPlanData, userId = null) {
  try {
    if (mongoose.connection.readyState !== 1) {
      console.warn('MongoDB not connected, skipping database save');
      return null;
    }

    const mealPlan = new MealPlan({
      userId: userId || undefined,
      weight: parseFloat(weight),
      height: parseFloat(height),
      healthConditions: conditions,
      weeklyPlan: mealPlanData.weeklyPlan,
      groceryList: mealPlanData.groceryList,
      totalCalories: mealPlanData.totalCalories
    });

    await mealPlan.save();
    return mealPlan._id;
  } catch (error) {
    console.error('Error saving meal plan to database:', error.message);
    return null;
  }
}

router.use(optionalAuth);

router.post('/generate', async (req, res) => {
  try {
    const { weight, height, healthConditions, includeGroceryList, forceRegenerate, dietPreference } = req.body || {};

    const parsedWeight = parseFiniteNumber(weight);
    if (parsedWeight === null || parsedWeight <= 0) {
      return res.status(400).json({ error: 'Valid weight is required' });
    }

    const parsedHeight = parseFiniteNumber(height);
    if (parsedHeight === null || parsedHeight <= 0) {
      return res.status(400).json({ error: 'Valid height is required' });
    }

    const conditions = normalizeHealthConditions(healthConditions);
    const includeList = parseBoolean(includeGroceryList, true);
    const validDietPrefs = ['vegetarian', 'non-vegetarian'];
    const diet = validDietPrefs.includes(dietPreference) ? dietPreference : 'non-vegetarian';
    const userId = getUserId(req);

    const startTime = Date.now();
    
    if (!forceRegenerate && mongoose.connection.readyState === 1) {
      try {
        const cachedPlan = await MealPlan.findCached(parsedWeight, parsedHeight, conditions, userId);
        
        if (cachedPlan) {
          const cacheTime = Date.now() - startTime;
          console.log(`✅ Cached meal plan found in ${cacheTime}ms (ID: ${cachedPlan._id})`);
          
          return res.json({
            success: true,
            cached: true,
            mealPlan: {
              id: cachedPlan._id,
              weeklyPlan: cachedPlan.weeklyPlan,
              groceryList: cachedPlan.groceryList || [],
              totalCalories: cachedPlan.totalCalories,
              healthConditions: cachedPlan.healthConditions,
              weight: cachedPlan.weight,
              height: cachedPlan.height,
              createdAt: cachedPlan.createdAt
            }
          });
        }
      } catch (cacheError) {
        console.warn('Cache lookup failed, proceeding with AI generation:', cacheError.message);
      }
    }
    
    const mealPlanData = await generateWeeklyMealPlan(
      parsedWeight,
      parsedHeight,
      conditions,
      includeList,
      diet
    );
    
    const generationTime = Date.now() - startTime;
    console.log(`⏱️  Meal plan generated by AI in ${generationTime}ms`);

    const savedId = await saveMealPlanToDatabase(parsedWeight, parsedHeight, conditions, mealPlanData, userId);

    const responseData = {
      success: true,
      cached: false,
      mealPlan: {
        id: savedId || 'temp-' + Date.now(),
        weeklyPlan: mealPlanData.weeklyPlan,
        groceryList: mealPlanData.groceryList || [],
        totalCalories: mealPlanData.totalCalories,
        healthConditions: conditions,
        weight: parsedWeight,
        height: parsedHeight
      }
    };

    res.json(responseData);
  } catch (error) {
    console.error('❌ Error generating meal plan:', error);
    console.error('   Message:', error.message);
    console.error('   Code:', error.errorCode || 'N/A');
    
    res.status(500).json({ 
      error: error.userMessage || 'Failed to generate meal plan',
      details: error.userDetails || error.message,
      code: error.errorCode || 'UNKNOWN_ERROR',
      help: getErrorHelp(error.errorCode)
    });
  }
});

