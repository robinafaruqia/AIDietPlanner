router.get('/history/list', async (req, res) => {
  try {
    if (mongoose.connection.readyState !== 1) {
      return res.json({ success: true, history: [], message: 'Database not connected' });
    }

    const limit = Math.min(Math.max(parseInt(req.query.limit) || 20, 1), 50);
    const skip = Math.max(parseInt(req.query.skip) || 0, 0);
    const userId = getUserId(req);

    const query = userId ? { userId } : {};

    const mealPlans = await MealPlan.find(query)
      .select('weight height healthConditions totalCalories createdAt')
      .sort({ createdAt: -1 })
      .skip(skip)
      .limit(limit);

    const total = await MealPlan.countDocuments(query);

    const history = mealPlans.map(plan => ({
      id: plan._id,
      weight: plan.weight,
      height: plan.height,
      healthConditions: plan.healthConditions || [],
      totalCalories: plan.totalCalories,
      createdAt: plan.createdAt
    }));

    res.json({ 
      success: true, 
      history,
      pagination: {
        total,
        limit,
        skip,
        hasMore: skip + limit < total
      }
    });
  } catch (error) {
    console.error('Error fetching meal plan history:', error);
    res.status(500).json({ error: 'Failed to fetch history' });
  }
});

router.get('/:id', async (req, res) => {
  try {
    if (!mongoose.isValidObjectId(req.params.id)) {
      return res.status(400).json({ error: 'Invalid meal plan id' });
    }
    
    const userId = getUserId(req);
    const query = { _id: req.params.id };
    
    if (userId) {
      query.userId = userId;
    }
    
    const mealPlan = await MealPlan.findOne(query);
    if (!mealPlan) {
      return res.status(404).json({ error: 'Meal plan not found' });
    }
    res.json({ success: true, mealPlan });
  } catch (error) {
    console.error('Error fetching meal plan:', error);
    res.status(500).json({ error: 'Failed to fetch meal plan' });
  }
});

